#!/usr/bin/env node
// Generate the static crypto fixtures embedded in src/fixtures.js.
//
// Run OFFLINE with Node's WebCrypto (never at edge runtime):
//   node tools/platform-probe/scripts/gen-crypto-fixtures.mjs
//
// Produces a throwaway HMAC-SHA256 key + MAC and an RSA-2048 public JWK +
// RS256 signature over a JWT-shaped signing input. The RSA private key is
// discarded; the HMAC key is a test-only value used for nothing else. None of
// these are secrets — they exist only so /__probe/crypto can time verify().
import { webcrypto as wc } from "node:crypto";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const b64u = (buf) => Buffer.from(buf).toString("base64url");
const enc = new TextEncoder();

const header = b64u(enc.encode(JSON.stringify({ alg: "RS256", typ: "JWT", kid: "probe-test" })));
const payload = b64u(enc.encode(JSON.stringify({
  iss: "https://probe.invalid/", sub: "probe", aud: "probe", iat: 1700000000, exp: 1700003600,
  "https://oidc.workers.dev/groups": ["medical", "market-access"],
})));
const message = `${header}.${payload}`;

const hmacRaw = wc.getRandomValues(new Uint8Array(32));
const hmacKey = await wc.subtle.importKey("raw", hmacRaw, { name: "HMAC", hash: "SHA-256" }, false, ["sign"]);
const hmacSig = await wc.subtle.sign("HMAC", hmacKey, enc.encode(message));

const rsa = await wc.subtle.generateKey(
  { name: "RSASSA-PKCS1-v1_5", modulusLength: 2048, publicExponent: new Uint8Array([1, 0, 1]), hash: "SHA-256" },
  true, ["sign", "verify"]);
const rsaSig = await wc.subtle.sign("RSASSA-PKCS1-v1_5", rsa.privateKey, enc.encode(message));
const jwk = await wc.subtle.exportKey("jwk", rsa.publicKey);

const out = `// GENERATED by scripts/gen-crypto-fixtures.mjs — do not edit by hand.
// Test-only crypto material for /__probe/crypto timings. NOT secrets: the RSA
// private key was discarded at generation time and the HMAC key protects nothing.

/** JWT-shaped signing input (header.payload, base64url). */
export const MESSAGE = ${JSON.stringify(message)};

/** 32-byte HMAC-SHA256 key, base64url. */
export const HMAC_KEY_B64U = ${JSON.stringify(b64u(hmacRaw))};
/** HMAC-SHA256(MESSAGE), base64url. */
export const HMAC_SIG_B64U = ${JSON.stringify(b64u(hmacSig))};

/** RSA-2048 public key (as served in a JWKS). */
export const RSA_PUBLIC_JWK = ${JSON.stringify({ kty: jwk.kty, n: jwk.n, e: jwk.e, alg: "RS256", ext: true })};
/** RS256 (RSASSA-PKCS1-v1_5 / SHA-256) signature over MESSAGE, base64url. */
export const RSA_SIG_B64U = ${JSON.stringify(b64u(rsaSig))};
`;

const target = fileURLToPath(new URL("../src/fixtures.js", import.meta.url));
writeFileSync(target, out);
console.log(`wrote ${target}`);
